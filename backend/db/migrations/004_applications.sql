CREATE TABLE applications (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
    candidate_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
    full_name text NOT NULL,
    email text NOT NULL CHECK (email = lower(trim(email))),
    phone text,
    source text,
    applied_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    status text NOT NULL DEFAULT 'applied' CHECK (status IN (
        'applied','screened','shortlisted','interview_scheduled','interviewed',
        'feedback_received','selected','rejected','hold','offer_sent','onboarding','complete'
    )),
    resume_path text,
    resume_text text,
    parsed_data jsonb,
    experience_years numeric CHECK (experience_years >= 0),
    embedding vector(384),
    parsed_at timestamptz,
    match_score double precision CHECK (match_score BETWEEN 0 AND 1),
    score_breakdown jsonb,
    explanation text,
    shortlisted boolean NOT NULL DEFAULT false,
    pending_approval text CHECK (pending_approval IN ('reject','offer')),
    approved_by bigint REFERENCES users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    offer_status text CHECK (offer_status IN ('draft','sent','accepted','declined')),
    offer_salary numeric CHECK (offer_salary >= 0),
    offer_joining_date date,
    offer_letter_path text,
    offer_sent_at timestamptz,
    UNIQUE (job_id, email)
);
